"""Bake adbperfetto/_buildinfo.py from git before a PyInstaller build.

build.bat runs this before PyInstaller and deletes the file afterwards;
the packaged exe imports it instead of shelling out to git at runtime.

Run:  .venv\\Scripts\\python tools\\write_buildinfo.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from adbperfetto import VERSION_BASE  # noqa: E402
from adbperfetto.versioning import from_git  # noqa: E402

OUT = ROOT / "adbperfetto" / "_buildinfo.py"


def main() -> int:
    version, build = from_git(VERSION_BASE, ROOT)
    OUT.write_text(
        "# Generated by tools/write_buildinfo.py; do not commit.\n"
        f'VERSION = "{version}"\n'
        f'BUILD = "{build}"\n',
        encoding="utf-8")
    print(f"Wrote {OUT.name}: VERSION={version} BUILD={build}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
